$ErrorActionPreference = 'Stop'

if (-not (Get-Command flutter -ErrorAction SilentlyContinue)) {
    throw 'Flutter SDK is not on PATH. Install Flutter and add its bin folder to PATH first.'
}

# Gradle wrapper JAR is binary and is not committed here. Generate a clean
# Flutter Android scaffold in a temporary directory and copy only the missing
# wrapper files into this project without overwriting custom configuration.
$scaffold = Join-Path $env:TEMP 'cloudcar_flutter_scaffold'
if (Test-Path $scaffold) {
    Remove-Item $scaffold -Recurse -Force
}
New-Item -ItemType Directory -Path $scaffold -Force | Out-Null

Push-Location $scaffold
try {
    flutter create --org com.cloudcar --platforms=android --project-name cloud_car .
} finally {
    Pop-Location
}

$wrapperFiles = @(
    'android\gradlew',
    'android\gradlew.bat',
    'android\gradle\wrapper\gradle-wrapper.jar'
)

foreach ($relative in $wrapperFiles) {
    $source = Join-Path $scaffold $relative
    $destination = Join-Path (Get-Location) $relative

    if ((Test-Path $source) -and -not (Test-Path $destination)) {
        New-Item -ItemType Directory -Force -Path (Split-Path $destination) | Out-Null
        Copy-Item $source $destination
        Write-Host "Added $relative"
    }
}

# Copy standard launcher icon resources generated by Flutter if they are absent.
$resRoot = Join-Path $scaffold 'android\app\src\main\res'
if (Test-Path $resRoot) {
    $targetResRoot = Join-Path (Get-Location) 'android\app\src\main\res'
    Get-ChildItem -Path $resRoot -Directory -Filter 'mipmap-*' | ForEach-Object {
        $destination = Join-Path $targetResRoot $_.Name
        if (-not (Test-Path $destination)) {
            Copy-Item $_.FullName $destination -Recurse
            Write-Host "Added launcher resources: $($_.Name)"
        }
    }
}

flutter pub get
Write-Host 'Bootstrap complete. Run scripts\build_apk.ps1 to build the release APK.'
